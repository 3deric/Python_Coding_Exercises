def mergesort(data : list) -> list:
    if len(data) <= 1:
        return data

    pivot = len(data) // 2 # pivotpoint for splitting
    left = mergesort(data[:pivot])
    right = mergesort(data[pivot:])

    result = []

    while left and right:
        if left[0] < right[0]:
            result.append(left.pop(0))
        else:
            result.append(right.pop(0))

    result += left
    result += right

    return result

