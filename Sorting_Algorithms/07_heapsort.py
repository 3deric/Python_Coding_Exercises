def build_heap(data, i, size) :
    largest = i
    left = 2 * i + 1
    right = 2 * i + 2

    if left < size and data[left] > data[largest]:
        largest = left
    if right < size and data[right] > data[largest]:
        largest = right
    if largest != i:
        data[i], data[largest] = data[largest], data[i]
        build_heap(data, largest, size)

def heapsort(data : list) -> list:
    n = len(data)
    for i in range(n // 2 - 1, -1, -1):
        build_heap(data, i, n)

    for i in range(n - 1, 0, -1):
        data[0], data[i] = data[i], data[0]
        build_heap(data,0, i)

    return data

